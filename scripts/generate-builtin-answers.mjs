/**
 * Writes functions/lib/builtinCorrect.ts — id → { correctIndex, categorySlug }.
 * Run from build / check so the worker never trusts the client.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'src', 'data', 'questions')
const out = join(root, 'functions', 'lib', 'builtinCorrect.ts')

function extractExplanation(block) {
  const backtick = block.match(/explanation:\s*`([\s\S]*?)`/s)
  if (backtick) return backtick[1].trim()

  const single = block.match(/explanation:\s*'((?:\\'|[\s\S])*?)'/s)
  if (single) return single[1].replace(/\\'/g, "'").trim()

  const double = block.match(/explanation:\s*"((?:\\"|[\s\S])*?)"/s)
  if (double) return double[1].replace(/\\"/g, '"').trim()

  return ''
}

/** @type {Record<string, { correctIndex: number; categorySlug: string; explanation: string }>} */
const map = {}
for (const file of readdirSync(dir).filter((f) => f.endsWith('.ts'))) {
  const text = readFileSync(join(dir, file), 'utf8')
  const idHits = [...text.matchAll(/id:\s*['"]([^'"]+)['"]/g)]
  for (let i = 0; i < idHits.length; i++) {
    const id = idHits[i][1]
    const start = idHits[i].index
    const end = i + 1 < idHits.length ? idHits[i + 1].index : text.length
    const block = text.slice(start, end)
    const correctIndex = Number(block.match(/correctIndex:\s*(\d+)/)?.[1])
    const categorySlug = block.match(/categorySlug:\s*['"]([^'"]+)['"]/)?.[1]
    const explanation = extractExplanation(block)
    if (!Number.isNaN(correctIndex) && categorySlug) {
      map[id] = { correctIndex, categorySlug, explanation }
    }
  }
}

const body = `/** Generated by scripts/generate-builtin-answers.mjs — do not edit. */
export type BuiltinAnswer = {
  correctIndex: number
  categorySlug: string
  explanation: string
}

export const BUILTIN_ANSWERS: Record<string, BuiltinAnswer> = ${JSON.stringify(map, null, 2)}
`

writeFileSync(out, body)
console.log(`Wrote ${out} (${Object.keys(map).length} questions)`)

